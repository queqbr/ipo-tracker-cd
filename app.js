$('#q').addEventListener('input', e => { state.q = e.target.value; render(); });
$('#xchg').addEventListener('change', e => { state.exchange = e.target.value; render(); });
$('#status').addEventListener('change', e => { state.status = e.target.value; render(); });
$('#csvBtn').addEventListener('click', exportCsv);
$('#clearBtn').addEventListener('click', clearAll);

$('#watchBtn').addEventListener('click', e => {
  state.watchOnly = !state.watchOnly;
  e.currentTarget.classList.toggle('on', state.watchOnly);
  e.currentTarget.setAttribute('aria-pressed', state.watchOnly);
  render();
});

$('#sectors').addEventListener('click', e => {
  const b = e.target.closest('[data-sector]');
  if (!b) return;
  state.sector = b.dataset.sector;
  document.querySelectorAll('#sectors .chip').forEach(c => c.classList.toggle('on', c === b));
  render();
});

$('#rail').addEventListener('click', e => {
  const b = e.target.closest('[data-month]');
  if (!b) return;
  state.month = (state.month === b.dataset.month) ? '' : b.dataset.month;
  renderRail(); render();
});

document.querySelector('thead').addEventListener('click', e => {
  const th = e.target.closest('th.sortable');
  if (!th) return;
  const k = th.dataset.k;
  if (state.sort !== k) { state.sort = k; state.dir = 1; }        // new column: ascending
  else if (state.dir === 1) state.dir = -1;                       // 2nd click: descending
  else state.sort = null;                                          // 3rd click: back to unsorted
  render();
});
document.querySelectorAll('thead th.sortable').forEach(th => {
  th.tabIndex = 0;
  th.addEventListener('keydown', e => {
    if (e.key === 'Enter' || e.key === ' '){ e.preventDefault(); th.click(); }
  });
});

$('#tbody').addEventListener('click', e => {
  const t = e.target.closest('[data-toggle]');
  if (t){
    const co = t.dataset.toggle;
    state.open.has(co) ? state.open.delete(co) : state.open.add(co);
    return render();
  }
  const s = e.target.closest('[data-star]');
  if (s){
    const co = s.dataset.star;
    watch.has(co) ? watch.delete(co) : watch.add(co);
    store.set('ipo.watchlist', JSON.stringify([...watch]));
    toast(watch.has(co) ? 'Saved to watchlist' : 'Removed from watchlist');
    return render();
  }
  const c = e.target.closest('[data-copy]');
  if (c) copy(c.dataset.copy);
});

function clearAll(){
  state.q = ''; state.exchange = ''; state.sector = ''; state.status = '';
  state.month = ''; state.watchOnly = false; state.sort = null; state.dir = 1;
  $('#q').value = ''; $('#xchg').value = ''; $('#status').value = '';
  $('#watchBtn').classList.remove('on');
  $('#watchBtn').setAttribute('aria-pressed','false');
  document.querySelectorAll('#sectors .chip').forEach((c,i) => c.classList.toggle('on', i === 0));
  renderRail(); render();
}

